export function generateRandomLine(chars: number): string {
  let result = "";
  while (result.length < chars) {
    const word = WORDS[Math.floor(Math.random() * WORDS.length)];
    result += (result.length === 0 ? "" : " ") + word;
  }
  return result.slice(0, chars).trimEnd();
}
